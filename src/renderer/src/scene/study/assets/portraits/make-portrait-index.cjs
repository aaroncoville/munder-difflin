'use strict';
/**
 * Rewrite `../../portraits.index.ts` from whatever image files sit in this
 * directory.
 *
 * The index exists because the pack is a drop-in folder, and a bundler needs a
 * static import per file to actually emit and fingerprint one. Generating the
 * imports keeps "what is on disk" and "what the app ships" the same list, and
 * a test holds the two against each other so a portrait added without running
 * this script fails loudly instead of quietly never appearing.
 *
 * It emits the NAMES beside the files, in the same order, because an import
 * yields a fingerprinted URL and the filename is gone by the time the app sees
 * it. Names are what lets an assistant called `leo` wear `leo.png` — which is
 * the whole point of spawning workers from a pool of portrait names — and
 * without them the app could only ever hash an id into the pack.
 *
 * Run from this directory: `node make-portrait-index.cjs`
 */
const fs = require('node:fs');
const path = require('node:path');

const files = fs.readdirSync(__dirname)
  .filter((f) => /\.(png|jpe?g|webp)$/i.test(f))
  .sort();

const ident = (f, i) => `p${i}_${f.replace(/\.[^.]+$/, '').replace(/[^A-Za-z0-9]/g, '_')}`;

const nameOf = (f) => f.replace(/\.[^.]+$/, '');

const body = files.length
  ? `${files.map((f, i) => `import ${ident(f, i)} from './assets/portraits/${f}';`).join('\n')}\n\n` +
    `export const PORTRAIT_FILES: string[] = [\n${files.map((f, i) => `  ${ident(f, i)}`).join(',\n')}\n];\n\n` +
    `/** The portraits' own names, index for index with PORTRAIT_FILES. */\n` +
    `export const PORTRAIT_NAMES: string[] = [\n${files.map((f) => `  '${nameOf(f)}'`).join(',\n')}\n];\n`
  : 'export const PORTRAIT_FILES: string[] = [];\n\nexport const PORTRAIT_NAMES: string[] = [];\n';

fs.writeFileSync(path.join(__dirname, '..', '..', 'portraits.index.ts'),
  `// GENERATED by assets/portraits/make-portrait-index.cjs — do not edit by hand.\n` +
  `// Re-run it whenever the portrait pack changes; a test checks this list\n` +
  `// against the directory, so a stale index fails the suite.\n${body}`);

process.stdout.write(`[portrait-index] ${files.length} portrait(s)\n`);
